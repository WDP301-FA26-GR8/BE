import type { NestedClassification, RegistryEvent } from './api-collection-registry';

export const closedException = (
  key: string,
  finding: string,
  item: string,
  reason: string,
  date: RegistryEvent['date'] = '2026-10-23',
): RegistryEvent => ({ registry: 'exceptions', key, change: 'closed', finding, item, date, reason });

/** The entry of an operation the compatibility release removed (spec L.6): the live registry loses it, the frozen one keeps it. */
export const removedOperation = (
  registry: RegistryEvent['registry'],
  key: string,
  finding: string,
  reason: string,
  from?: NestedClassification,
): RegistryEvent => ({
  registry,
  key,
  change: 'closed',
  ...(from === undefined ? {} : { from }),
  finding,
  item: 'g0-g6-final-business-baseline-remediation',
  date: '2026-10-28',
  reason,
});

export const boundedNested = (
  key: string,
  bound: string,
  finding: string,
  item: string,
  reason: string,
  change: 'reclassified' | 'added' = 'reclassified',
): RegistryEvent => ({
  registry: 'nested',
  key,
  change,
  ...(change === 'reclassified' ? { from: 'unbounded' as const } : {}),
  to: 'bounded',
  bound,
  finding,
  item,
  date: '2026-10-23',
  reason,
});

