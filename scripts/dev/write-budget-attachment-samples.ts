import * as crypto from 'crypto';
import * as fs from 'fs';
import * as path from 'path';
import { buildSampleFiles, type SampleManifestEntry } from '../../test/support/budget-attachment-samples';

const ROOT_DIR = path.resolve(__dirname, '..', '..');
const EXAMPLES_DIR = path.join(ROOT_DIR, 'docs', 'examples', 'budget-attachments');
const FILES_DIR = path.join(EXAMPLES_DIR, 'files');
const MANIFEST_PATH = path.join(EXAMPLES_DIR, 'manifest.json');

function main(): void {
  const isCheck = process.argv.includes('--check');
  const samples = buildSampleFiles();

  if (isCheck) {
    if (!fs.existsSync(MANIFEST_PATH)) {
      console.error(`Check failed: manifest does not exist at ${MANIFEST_PATH}`);
      process.exit(1);
    }

    const manifestRaw = fs.readFileSync(MANIFEST_PATH, 'utf-8');
    const manifest = JSON.parse(manifestRaw) as SampleManifestEntry[];

    if (manifest.length !== samples.length) {
      console.error(`Check failed: manifest has ${manifest.length} entries, expected ${samples.length}`);
      process.exit(1);
    }

    for (const sample of samples) {
      const entry = manifest.find((m) => m.file === sample.file);
      if (!entry) {
        console.error(`Check failed: missing entry in manifest for ${sample.file}`);
        process.exit(1);
      }
      if (entry.sizeBytes !== sample.sizeBytes || entry.sha256 !== sample.sha256) {
        console.error(`Check failed: manifest mismatch for ${sample.file}`);
        process.exit(1);
      }

      const filePath = path.join(FILES_DIR, sample.file);
      if (!fs.existsSync(filePath)) {
        console.error(`Check failed: file does not exist on disk: ${filePath}`);
        process.exit(1);
      }

      const diskContent = fs.readFileSync(filePath);
      const diskSha256 = crypto.createHash('sha256').update(diskContent).digest('hex');
      if (diskContent.length !== sample.sizeBytes || diskSha256 !== sample.sha256) {
        console.error(
          `Check failed: content mismatch for ${sample.file} on disk (disk: ${diskContent.length} bytes / ${diskSha256}, expected: ${sample.sizeBytes} bytes / ${sample.sha256})`,
        );
        process.exit(1);
      }
    }

    // Check no extra files on disk
    if (fs.existsSync(FILES_DIR)) {
      const diskFiles = fs.readdirSync(FILES_DIR);
      for (const diskFile of diskFiles) {
        if (!samples.some((s) => s.file === diskFile)) {
          console.error(`Check failed: unexpected extra file on disk: ${diskFile}`);
          process.exit(1);
        }
      }
    }

    console.log('Sample files and manifest match the generated bytes.');
    return;
  }

  // Write mode
  fs.mkdirSync(FILES_DIR, { recursive: true });

  const manifestEntries: SampleManifestEntry[] = [];

  for (const sample of samples) {
    const filePath = path.join(FILES_DIR, sample.file);
    fs.writeFileSync(filePath, sample.content);

    manifestEntries.push({
      file: sample.file,
      contentType: sample.contentType,
      sizeBytes: sample.sizeBytes,
      sha256: sample.sha256,
      declare: sample.declare,
      complete: sample.complete,
    });
  }

  const manifestJson = JSON.stringify(manifestEntries, null, 2) + '\n';
  fs.writeFileSync(MANIFEST_PATH, manifestJson, 'utf-8');
  console.log(`Wrote ${samples.length} sample files and manifest to ${EXAMPLES_DIR}`);
}

try {
  main();
} catch (err) {
  console.error(err);
  process.exit(1);
}
