// pnpm arch:graph — writes docs/generated/module-graph.md: the business modules by tier and every module-to-module
// import edge (production code, specs excluded), as a Mermaid diagram GitHub renders. `--check` fails when stale.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { moduleEdges } from './module-edges.mjs';

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const { TIERS } = require('./tiers.cjs');
const target = join(root, 'docs', 'generated', 'module-graph.md');

function render(edges) {
  const id = (name) => name.replace(/-/g, '_');
  const lines = [
    '# Module graph',
    '',
    'Generated by `pnpm arch:graph`; do not edit by hand. Tiers come from `scripts/arch/tiers.cjs`; an arrow is',
    '"imports" (number = import statements). The gate `pnpm arch:check` refuses any arrow that points up a tier.',
    '',
    '```mermaid',
    'flowchart BT',
  ];
  TIERS.forEach((tier, index) => {
    lines.push(`  subgraph T${index + 1}["T${index + 1}"]`);
    for (const name of tier) lines.push(`    ${id(name)}["${name}"]`);
    lines.push('  end');
  });
  for (const [key, count] of edges) {
    const [from, to] = key.split('>');
    lines.push(`  ${id(from)} -->|${count}| ${id(to)}`);
  }
  lines.push('```', '', `${edges.length} module edges.`, '');
  return lines.join('\n');
}

const text = render(moduleEdges(root));
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    // missing file: reported below
  }
  if (current !== text) {
    console.error('docs/generated/module-graph.md is out of date: run `pnpm arch:graph` and commit it.');
    process.exitCode = 1;
  }
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, text);
  console.log(`docs/generated/module-graph.md written`);
}
