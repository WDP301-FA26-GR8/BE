// pnpm arch:routes — writes docs/generated/routes.md: every OpenAPI operation → controller file → the services its
// handler calls. The map a person uses to find the code of a route without searching (spec D9, Task 0.2).
// Reads openapi.json (operationId) and the controllers (`operationId: '…'` in @ApiOperation); no app is started.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ts = require('typescript');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const posix = (p) => p.split(sep).join('/');

const walk = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : e.name.endsWith('.controller.ts') ? [join(dir, e.name)] : [],
  );

/** operationId → { controller, handler, services: [{ name, file }] } */
function scanControllers() {
  const byOperation = new Map();
  for (const file of walk(join(root, 'src'))) {
    const source = ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
    const imports = new Map(); // class name -> repo-relative file
    for (const statement of source.statements) {
      if (!ts.isImportDeclaration(statement) || !statement.importClause?.namedBindings) continue;
      const spec = statement.moduleSpecifier.text;
      if (!spec.startsWith('.')) continue;
      const target = posix(relative(root, resolve(dirname(file), spec))) + '.ts';
      const bindings = statement.importClause.namedBindings;
      if (ts.isNamedImports(bindings)) for (const el of bindings.elements) imports.set(el.name.text, target);
    }
    ts.forEachChild(source, function visit(node) {
      if (!ts.isClassDeclaration(node)) return ts.forEachChild(node, visit);
      const fields = new Map(); // constructor field -> class name
      const ctor = node.members.find(ts.isConstructorDeclaration);
      for (const param of ctor?.parameters ?? []) {
        if (param.type && ts.isTypeReferenceNode(param.type) && ts.isIdentifier(param.name)) {
          fields.set(param.name.text, param.type.typeName.getText(source));
        }
      }
      for (const member of node.members) {
        if (!ts.isMethodDeclaration(member)) continue;
        const operation = (ts.getDecorators(member) ?? [])
          .map((d) => /operationId:\s*'([^']+)'/.exec(d.getText(source))?.[1])
          .find(Boolean);
        if (!operation) continue;
        const called = new Set();
        const body = member.body?.getText(source) ?? '';
        for (const match of body.matchAll(/this\.([A-Za-z0-9_]+)\./g)) {
          const type = fields.get(match[1]);
          if (type) called.add(type);
        }
        byOperation.set(operation, {
          controller: posix(relative(root, file)),
          handler: member.name.getText(source),
          services: [...called].map((name) => ({ name, file: imports.get(name) })),
        });
      }
    });
  }
  return byOperation;
}

export function buildRoutes() {
  const openapi = JSON.parse(readFileSync(join(root, 'openapi.json'), 'utf8'));
  const byOperation = scanControllers();
  const rows = [];
  const missing = [];
  for (const [path, item] of Object.entries(openapi.paths)) {
    for (const [method, operation] of Object.entries(item)) {
      if (!operation?.operationId) continue;
      const found = byOperation.get(operation.operationId);
      if (!found) missing.push(`${method.toUpperCase()} ${path} (${operation.operationId})`);
      rows.push({ method: method.toUpperCase(), path, operation, found });
    }
  }
  return { rows, missing };
}

function render(rows) {
  const link = (file, text = file.replace(/^src\/modules\//, '')) => `[${text}](../../${file})`;
  const lines = [
    '# Routes → code',
    '',
    'Generated by `pnpm arch:routes` from `openapi.json` and the controllers; do not edit by hand.',
    'Find a route, open its controller, then the service it calls. Module of a file = the folder after `src/modules/`.',
    '',
    '| Method | Path | Controller → handler | Services called |',
    '| --- | --- | --- | --- |',
  ];
  for (const { method, path, found } of rows) {
    const controller = found ? `${link(found.controller)} → \`${found.handler}\`` : '(not found)';
    const services = found?.services.map((s) => (s.file ? link(s.file, s.name) : s.name)).join(', ') ?? '';
    lines.push(`| ${method} | \`${path.replace('/api/v1', '')}\` | ${controller} | ${services} |`);
  }
  lines.push('', `${rows.length} operations.`, '');
  return lines.join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { rows, missing } = buildRoutes();
  const target = join(root, 'docs', 'generated', 'routes.md');
  const text = render(rows);
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      // missing file: reported below
    }
    if (current.replace(/\r\n/g, '\n') !== text) {
      console.error('docs/generated/routes.md is out of date: run `pnpm arch:routes` and commit it.');
      process.exitCode = 1;
    }
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, text);
    console.log(`docs/generated/routes.md: ${rows.length} operations`);
  }
  if (missing.length) {
    console.error(`No controller handler found for ${missing.length} operation(s):\n  ${missing.join('\n  ')}`);
    process.exitCode = 1;
  }
}
