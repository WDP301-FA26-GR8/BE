#!/usr/bin/env node
// Appends (or replaces) the "4.3.1" section of results/summary.md from the tagged result files. The 3.8.1 baseline text
// above the marker is never touched.   node tools/summary-431.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { POLARITY_CATEGORIES } from '../lib/metrics.mjs';

export const BEGIN = '<!-- BEGIN 4.3.1 (generated by tools/summary-431.mjs) -->';
export const END = '<!-- END 4.3.1 -->';

const fmt = (v, d = 1) =>
  v === null || v === undefined || Number.isNaN(v) ? 'n/a' : typeof v === 'number' ? v.toFixed(d) : String(v);

export function replaceMarked(text, block) {
  const b = text.indexOf(BEGIN);
  const e = text.indexOf(END);
  if (b !== -1 && e !== -1 && e > b) {
    const after = text.slice(e + END.length).replace(/^\n/, '');
    return text.slice(0, b) + block + after;
  }
  return text.replace(/\n*$/, '\n\n') + block;
}

function table(runs, labelOf) {
  const modes = ['raw', 'protected'].filter((m) => runs.some((r) => r.mode === m));
  const get = (m) => runs.find((r) => r.mode === m);
  const out = [`| Metric | ${modes.join(' | ')} |`, `|---|${modes.map(() => '---:').join('|')}|`];
  const row = (label, f) => out.push(`| ${label} | ${modes.map((m) => f(get(m))).join(' | ')} |`);
  row('Fields', (r) => String(r.fields.items));
  row('Fields translated (%)', (r) => fmt(r.fields.translatedPct));
  row('Fields fallen back to the exact original (%)', (r) => fmt(r.fields.fallback.pct));
  for (const b of ['placeholder', 'polarity', 'too_long', 'max_new_tokens', 'other'])
    row(`&nbsp;&nbsp;fallback: ${b} (fields)`, (r) => String(r.fields.fallback.byReason[b]));
  row('Corpus chrF, all fields (fallback = source text)', (r) => fmt(r.fields.chrF.corpus));
  row('chrF, translated fields only', (r) => fmt(r.fields.chrF.translatedOnly));
  row(
    'Protected terms preserved, translated fields (%)',
    (r) => `${fmt(r.fields.preservation.translatedPct)} (n=${r.fields.preservation.n})`,
  );
  row(
    'Automatic flags: keyword check failed on translated fields',
    (r) => `${r.fields.automaticFlags.meaningFlags} of ${r.fields.automaticFlags.translatedFields}`,
  );
  for (const c of POLARITY_CATEGORIES)
    row(
      `&nbsp;&nbsp;automatic flags, ${c} items`,
      (r) => `${r.fields.automaticFlags.polarity[c].flags} of ${r.fields.automaticFlags.polarity[c].n}`,
    );
  row('Automatic flags: protected term altered (translated fields)', (r) =>
    String(r.fields.automaticFlags.preservationFlags),
  );
  row(
    'Latency per field p50 / p95 (ms)',
    (r) => `${fmt(r.fields.latency.field.p50, 0)} / ${fmt(r.fields.latency.field.p95, 0)}`,
  );
  row(
    'Latency per segment p50 / p95 (ms)',
    (r) =>
      `${fmt(r.fields.latency.segment.p50, 0)} / ${fmt(r.fields.latency.segment.p95, 0)} (n=${r.fields.latency.segment.n})`,
  );
  row('Model load (s)', (r) => fmt(r.loadMs / 1000, 2));
  row('Peak RSS of process (MB)', (r) => fmt(r.peakRssMb, 0));
  void labelOf;
  return out;
}

export function renderSection431({ runs, baseline = [], tags = null, labels = {} }) {
  const out = [BEGIN, '', '## 4.3.1 (shared generate adapter, whole-field fallback)', ''];
  const first = runs[0];
  if (first) {
    const e = first.environment;
    out.push(
      `Run date ${first.date}. Environment: ${e.os}, ${e.cpuModel} (${e.cpuCount} logical CPUs, ${e.totalMemGb} GB RAM), Node ${e.node}, @huggingface/transformers ${e.transformers}. ` +
        `Lockfile sha256 \`${first.lockfile?.sha256 ?? 'n/a'}\` (${Object.entries(first.lockfile?.versions ?? {})
          .map(([k, v]) => `${k} ${v}`)
          .join(', ')}). ` +
        `Synthetic fixtures, AI-draft references (not human gold). "Automatic flags" are keyword / exact-string checks, not a judgement of quality, and nothing here is human reviewed.`,
      '',
    );
  }
  const allTags = tags ?? [...new Set(runs.map((r) => r.tag))];
  for (const tag of allTags) {
    const tagRuns = runs.filter((r) => r.tag === tag);
    const prefix = allTags.length > 1 ? `[${tag}] ${labels[tag] ? `${labels[tag]}: ` : ''}` : '';
    for (const set of ['main', 'heldout']) {
      for (const direction of ['vi-en', 'en-vi']) {
        const rs = tagRuns.filter((r) => r.fixtureSet === set && r.direction === direction);
        if (rs.length === 0) continue;
        out.push(
          `### ${prefix}${direction}, ${set === 'main' ? 'main fixtures' : 'held-out fixtures (written before the run, no tuning)'}`,
          '',
          ...table(rs),
          '',
        );
      }
    }
  }
  const mainRuns = runs.filter((r) => r.fixtureSet === 'main' && r.tag === allTags[0]);
  if (baseline.length > 0 && mainRuns.length > 0) {
    out.push(`### 3.8.1 baseline versus 4.3.1 (main fixtures${allTags.length > 1 ? `, tag ${allTags[0]}` : ''})`, '');
    out.push(
      'The baseline pipeline translated per sentence with partial fallback (segments that failed a gate kept the original); 4.3.1 uses whole-field fallback, polarity gate, 128-token segments. Baseline numbers come from the 2026-10-14 result files.',
      '',
    );
    for (const direction of ['vi-en', 'en-vi']) {
      const cols = [];
      for (const mode of ['raw', 'protected']) {
        const b = baseline.find((r) => r.direction === direction && r.mode === mode);
        if (b)
          cols.push({
            label: `3.8.1 ${mode}`,
            chrf: b.aggregate.corpusChrF,
            preserved: b.aggregate.preservedPct,
            silentPol: POLARITY_CATEGORIES.reduce((a, c) => a + b.aggregate.polarity[c].silentFailures, 0),
            fb: b.aggregate.fallbackSegmentPct,
            p50: b.aggregate.latency.p50,
            p95: b.aggregate.latency.p95,
          });
      }
      for (const mode of ['raw', 'protected']) {
        const r = mainRuns.find((x) => x.direction === direction && x.mode === mode);
        if (r)
          cols.push({
            label: `4.3.1 ${mode}`,
            chrf: r.aggregate.corpusChrF,
            preserved: r.aggregate.preservedPct,
            silentPol: POLARITY_CATEGORIES.reduce((a, c) => a + r.aggregate.polarity[c].silentFailures, 0),
            fb: r.fields.fallback.pct,
            p50: r.fields.latency.field.p50,
            p95: r.fields.latency.field.p95,
          });
      }
      out.push(
        `**${direction}**`,
        '',
        `| Metric | ${cols.map((c) => c.label).join(' | ')} |`,
        `|---|${cols.map(() => '---:').join('|')}|`,
      );
      out.push(`| Corpus chrF | ${cols.map((c) => fmt(c.chrf)).join(' | ')} |`);
      out.push(`| Items with all protected terms preserved (%) | ${cols.map((c) => fmt(c.preserved)).join(' | ')} |`);
      out.push(
        `| Silent polarity failures (items, keyword check, no fallback) | ${cols.map((c) => String(c.silentPol)).join(' | ')} |`,
      );
      out.push(`| Fallback (% segments for 3.8.1, % fields for 4.3.1) | ${cols.map((c) => fmt(c.fb)).join(' | ')} |`);
      out.push(
        `| Latency per item/field p50 / p95 (ms) | ${cols.map((c) => `${fmt(c.p50, 0)} / ${fmt(c.p95, 0)}`).join(' | ')} |`,
        '',
      );
    }
  }
  out.push(END, '');
  return out.join('\n');
}

const here = path.dirname(fileURLToPath(import.meta.url));
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const resultsDir = path.join(here, '..', 'results');
  const read = (f) => JSON.parse(fs.readFileSync(path.join(resultsDir, f), 'utf8'));
  const files = fs.readdirSync(resultsDir);
  const argTags = process.argv.includes('--tags')
    ? process.argv[process.argv.indexOf('--tags') + 1].split(',')
    : ['4.3.1b', '4.3.1'];
  const runs = files
    .filter((f) => /^\d{4}-\d\d-\d\d-4\.3\.1\w*-(main|heldout)-(vi-en|en-vi)-(raw|protected)\.json$/.test(f))
    .sort()
    .map(read)
    .filter((r) => argTags.includes(r.tag));
  const baseline = files
    .filter((f) => /^2026-10-14-(vi-en|en-vi)-(raw|protected)\.json$/.test(f))
    .sort()
    .map(read);
  const summaryPath = path.join(resultsDir, 'summary.md');
  const next = replaceMarked(
    fs.readFileSync(summaryPath, 'utf8'),
    renderSection431({
      runs,
      baseline,
      tags: argTags,
      labels: {
        '4.3.1b': 'final run, after the two polarity-lexicon bug fixes',
        '4.3.1': 'run 1, before the fixes (kept)',
      },
    }),
  );
  fs.writeFileSync(summaryPath, next, 'utf8');
  console.log(`summary.md: 4.3.1 section written from ${runs.length} run file(s); baseline text untouched`);
}
